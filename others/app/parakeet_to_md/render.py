"""Segments in, captions out.

The owner's rule for the output is narrow and explicit (2026-10-27): *"o .md ta bloated. so precisamos
do .md das legendas, nao generated ou outras coisas assim"*. So the document is the transcript and
nothing else - no front matter, no metadata table, no "generated by" line. What stays is what a person
reads: paragraphs, each opening with its timestamp, separated by a blank line.

Structure that is not metadata is still allowed and opt-in: `with_parts=True` adds a `## 00:10:00`
heading every ten minutes, which is what makes a three-hour file navigable.

The rules that make the text readable rather than one line per VAD segment:

* a **line** ends at a **sentence end** (`.` `?` `!`) - one sentence per timestamped line, which is how
  Sotto's `transcribe.py` structures its output (`sentence_segments`, 30 s cap). The owner asked for
  that structure explicitly on 2026-10-27: "imita a melhora de estruturacao do texto igual o sotto faz";
* a line also ends at a pause of `PAUSE_SECONDS` or when it reaches `PARAGRAPH_MAX_CHARS`, so a missing
  full stop cannot produce a wall of text;
* every paragraph opens with its **timestamp**;
* non-speech segments never reach here (dropped in `segments.normalize`).

Everything is a pure function of its inputs, so `tests/test_render.py` pins the exact output.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .segments import Segment, normalize

PAUSE_SECONDS = 1.6
PARAGRAPH_MAX_CHARS = 700
MAX_LINE_SECONDS = 30.0
PART_SECONDS = 600.0
_SENTENCE_END = re.compile(r"[.!?][\"')\]]?$")


@dataclass(frozen=True)
class Paragraph:
    start: float
    end: float
    text: str


@dataclass(frozen=True)
class Part:
    index: int
    start: float
    paragraphs: tuple[Paragraph, ...]


def fmt_time(seconds: float) -> str:
    """`HH:MM:SS`. Always hours: a transcript that mixes `04:12` and `1:04:12` is harder to scan."""
    total = int(round(max(0.0, seconds)))
    hours, rest = divmod(total, 3600)
    minutes, secs = divmod(rest, 60)
    return "%02d:%02d:%02d" % (hours, minutes, secs)


def paragraphs(segments: list[Segment], pause_seconds: float = PAUSE_SECONDS,
               max_chars: int = PARAGRAPH_MAX_CHARS,
               max_seconds: float = MAX_LINE_SECONDS) -> list[Paragraph]:
    """Group consecutive segments into lines - **one sentence per line**, the way Sotto does it.

    Sotto's `sentence_segments` (`H:\\sotto\\worker\\models\\parakeet-redux-onnx-int4\\transcribe.py:132`)
    ends a segment on `.`/`?`/`!` or at 30 s, and that is what the owner asked for here on 2026-10-27.
    Two safety valves stay, because our units are VAD chunks and not words: a long silence and a run of
    text with no full stop must not produce one unreadable line.
    """
    out: list[Paragraph] = []
    current: list[Segment] = []
    char_count = 0

    def flush() -> None:
        nonlocal current, char_count
        if not current:
            return
        text = " ".join(seg.text for seg in current).strip()
        if text:
            out.append(Paragraph(start=current[0].start, end=current[-1].end, text=text))
        current = []
        char_count = 0

    for seg in segments:
        if current:
            gap = seg.start - current[-1].end
            ends_sentence = bool(_SENTENCE_END.search(current[-1].text))
            too_long = (seg.end - current[0].start) > max_seconds
            if gap >= pause_seconds or char_count >= max_chars or too_long:
                flush()
            elif ends_sentence:
                # unconditionally: a finished sentence is a finished line
                flush()
        current.append(seg)
        char_count += len(seg.text) + 1
    flush()
    return out


def parts(items: list[Paragraph], part_seconds: float = PART_SECONDS) -> list[Part]:
    """Bucket paragraphs into fixed-length parts, by the paragraph's own start time."""
    if not items:
        return []
    buckets: dict[int, list[Paragraph]] = {}
    for para in items:
        key = int(para.start // part_seconds)
        buckets.setdefault(key, []).append(para)
    out: list[Part] = []
    for index, key in enumerate(sorted(buckets)):
        group = tuple(buckets[key])
        out.append(Part(index=index + 1, start=group[0].start, paragraphs=group))
    return out


def render(source_name: str, segments: list[Segment], with_parts: bool = False) -> str:
    """The transcript for one file: a title line, then timestamped paragraphs.

    `source_name` is used only for the title; the filename already carries the video's name, and
    repeating it in a metadata block is the bloat the owner removed.
    """
    segments = normalize(segments)
    stem = Path(source_name).stem
    paras = paragraphs(segments)

    if not segments:
        return "# %s\n\nNo speech detected in this file.\n" % stem

    lines: list[str] = ["# %s" % stem, ""]
    if not with_parts:
        for para in paras:
            lines.append("**[%s]** %s" % (fmt_time(para.start), para.text))
            lines.append("")
        return "\n".join(lines)

    for part in parts(paras):
        lines.append("## Part %d · %s" % (part.index, fmt_time(part.start)))
        lines.append("")
        for para in part.paragraphs:
            lines.append("**[%s]** %s" % (fmt_time(para.start), para.text))
            lines.append("")
    return "\n".join(lines)
